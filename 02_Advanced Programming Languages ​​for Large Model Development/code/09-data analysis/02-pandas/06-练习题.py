"""
年龄小于30的数据
查看销售部的员工
按部门降序排序，工资升序
"""

import pandas as pd

# 创建示例数据
df = pd.DataFrame(
    {
        '姓名': ['张三', '李四', '王五', '赵六', '钱七'],
        '年龄': [25, 30, 35, 28, 32],
        '部门': ['a技术部', 'b销售部', 'a技术部', 'c人事部', 'b销售部'],
        '工资': [5000, 7000, 6000, 5500, 7500],
    }
)


print("原始数据:")
print(df)

print("年龄小于30：\n", df[df['年龄'] < 30])
print("查看销售部：\n", df.query("部门 == 'b销售部'"))
print(
    "部门降序，工资升序：\n", df.sort_values(['部门', '工资'], ascending=[False, True])
)
