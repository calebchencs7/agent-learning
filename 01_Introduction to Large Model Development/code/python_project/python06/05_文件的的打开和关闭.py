# 文件的打开
"""
open(文件路径,文件模式,文件编码)
文件路径:
    绝对路径是以盘符开始的路径  E:/xx/xx/xx
    相对路径不是以盘符开始路径  ./xx/xx/xx   注意:  .:当前目录(可以省略)  ..:上级目录
文件模式:
    r和rb: 读取文件 注意:文件必须存在,如果不存在就报错
    w和wb: 覆盖写数据到文件  注意: 文件如果不存在就先创建在写入,存在就直接使用
    a和ab: 追加写数据到文件  注意: 文件如果不存在就先创建在写入,存在就直接使用
文件编码:
    utf8: 万国码  通用 最常用
    gbk: 主要针对中文的国际标准扩展,cp936本质就是gbk
close()
    不是必须的,但是建议用完就关闭,节省资源
"""

# 打开文件
f = open('../python06/test.txt', mode='r', encoding='utf-8')
print(f)
# 关闭文件
f.close()
