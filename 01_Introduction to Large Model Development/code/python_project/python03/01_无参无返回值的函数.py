# 需求: 定义一个求和的函数,一个求差值的函数
# 1.先定义函数
def get_sum():
    a = 30
    b = 20
    sum = a + b
    print(sum)


def get_diff():
    a = 20
    b = 30
    diff = a - b
    print(diff)


# 2.再调用函数
get_diff()
get_diff()
get_diff()

