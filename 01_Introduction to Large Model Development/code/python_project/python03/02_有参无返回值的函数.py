# 需求: 定义一个求和的函数,一个求差值的函数
# 1.先定义函数
def get_sum(a, b):
    print(a + b)


def get_diff(x, y):
    print(x - y)


# 2.再调用函数
get_sum(10, 20)
get_sum(30, 20)
get_diff(20, 10)
get_diff(20, 30)

