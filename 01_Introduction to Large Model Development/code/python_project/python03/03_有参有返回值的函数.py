# 需求: 定义一个求和的函数,一个求差值的函数
# 1.先定义函数
def get_sum(a, b):
    sum = a + b
    return sum


def get_diff(x, y):
    diff = x - y
    return diff


# 2.再调用函数
he1 = get_sum(10, 20)
print(he1 + 10)
cha1 = get_diff(20, 10)
print(cha1)

