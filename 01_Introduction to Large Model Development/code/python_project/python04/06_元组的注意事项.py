# 元组是不可变类型,列表是可变类型
# 元组嵌套不可变类型
t1 = (10, 3.14, "你好", (1, 2, 3))
# t1[-1] = (4,5,6)  # 此行报错,因为元组不支持修改
# t1[-1][0] = 4  # 此行报错,因为元组不支持修改

# 元组嵌套中有可变类型
t2 = (10, 3.14, "你好", [1, 2, 3])
print(t2)
# 本质元组中存储的是地址(地址1,地址2,地址3,地址4)
# id:查看10进制地址
print(id(t2[-1]))
print('---------------------')
# t2[-1] = [4,5,6]  # 此行报错,因为元组不支持修改
t2[-1][0] = 4  # 可以修改成功,原因是列表是可变类型,列表内容变了,地址没变
print(id(t2[-1]))
print(t2)
