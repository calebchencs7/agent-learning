# for循环是一种循环结构,用于遍历数据集中的每一个元素,并对每一个元素执行相同的操作。
# 所以for循环没有无限循环的风险,因为它会在遍历完数据集后自动结束。

# for循环核心功能就是遍历数据集
# 需求1: 已知字符串'黑马程序员',要求把每个字依次打印到控制台
name = "黑马程序员"
for i in name:
    print(i)
print("===============================")
# 需求2: 已知字符串'黑马程序员',要求用for循环计算一共多少个字符
# 循环外定义初始变量
count = 0
name = "黑马程序员"
for i in name:
    # 循环内计数(每次加1)
    count += 1
# 循环外使用最终结果
print(f"{name}中一共有{count}个字符")
